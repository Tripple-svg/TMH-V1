create table if not exists public.brand_reviews (
  id text primary key,
  full_name text not null,
  brand_name text not null,
  email text not null,
  whatsapp text not null,
  main_goal text,
  platform_type text not null check (platform_type in ('website', 'social', 'none')),
  social_platform text,
  social_link text,
  website_url text,
  screenshot_url text,
  haven_score integer check (haven_score between 0 and 100),
  assessment_summary text,
  biggest_leak text,
  biggest_problems text[] default '{}',
  pre_call_briefing text,
  lead_temperature text default 'Cold' check (lead_temperature in ('Hot', 'Warm', 'Cold')),
  is_returning_user boolean default false,
  clicked_booking_link boolean default false,
  clicked_booking_at timestamptz,
  clicked_playbook_link boolean default false,
  clicked_playbook_at timestamptz,
  converted_to_call boolean default false,
  converted_to_purchase boolean default false,
  deal_value numeric,
  utm_source text,
  utm_campaign text,
  referrer_url text,
  device_type text,
  country text,
  city text,
  visit_count integer default 1 check (visit_count > 0),
  first_visit_at timestamptz default now(),
  submitted_at timestamptz default now(),
  days_to_convert integer default 0,
  followup_status text default 'pending' check (followup_status in ('pending', 'contacted', 'booked', 'closed', 'lost')),
  followup_notes text,
  call_booked_at timestamptz,
  welcome_email_sent boolean default false,
  booking_whatsapp_sent boolean default false,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.haven_sessions (
  id text primary key,
  review_id text references public.brand_reviews(id) on delete set null,
  scope text not null,
  service_id text,
  messages jsonb default '[]'::jsonb,
  current_step text default 'GREETING',
  last_step_reached text,
  total_exchanges integer default 0,
  drop_off_at timestamptz,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.link_click_events (
  id bigint generated by default as identity primary key,
  review_id text references public.brand_reviews(id) on delete set null,
  session_id text references public.haven_sessions(id) on delete set null,
  link_type text not null check (link_type in ('booking', 'playbook', 'whatsapp', 'tiktok', 'instagram')),
  clicked_at timestamptz default now()
);

create table if not exists public.strategy_call_bookings (
  id bigint generated by default as identity primary key,
  review_id text references public.brand_reviews(id) on delete set null,
  full_name text not null,
  email text not null,
  whatsapp text not null,
  brand_name text,
  booked_date date not null,
  booked_time text not null check (booked_time in ('5:00 PM', '5:30 PM', '6:00 PM', '6:30 PM', '7:00 PM', '7:30 PM')),
  status text default 'confirmed' check (status in ('confirmed', 'cancelled', 'completed', 'no_show')),
  confirmation_email_sent boolean default false,
  confirmation_whatsapp_sent boolean default false,
  whatsapp_message_template text,
  created_at timestamptz default now()
);

-- Prevent two confirmed appointments being made for the same published slot.
create unique index if not exists one_active_booking_per_slot
  on public.strategy_call_bookings (booked_date, booked_time)
  where status <> 'cancelled';

create table if not exists public.cookie_consents (
  id bigint generated by default as identity primary key,
  visitor_id text,
  consented boolean not null,
  created_at timestamptz default now()
);

create or replace function public.update_updated_at_column()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists update_brand_reviews_updated_at on public.brand_reviews;
create trigger update_brand_reviews_updated_at
before update on public.brand_reviews
for each row execute procedure public.update_updated_at_column();

