create or replace view public.available_booking_slots as
with dates as (
  select generate_series(current_date, current_date + interval '30 days', interval '1 day')::date as slot_date
), slots as (
  select slot_date, unnest(array['5:00 PM', '5:30 PM', '6:00 PM', '6:30 PM', '7:00 PM', '7:30 PM']) as slot_time
  from dates where extract(dow from slot_date) between 1 and 5
), booked as (
  select booked_date, booked_time from public.strategy_call_bookings where status <> 'cancelled'
)
select slots.slot_date, slots.slot_time, (booked.booked_date is null) as is_available
from slots left join booked on booked.booked_date = slots.slot_date and booked.booked_time = slots.slot_time
order by slots.slot_date, slots.slot_time;

create or replace view public.admin_lead_overview as
select br.*, hs.total_exchanges, hs.last_step_reached, hs.drop_off_at
from public.brand_reviews br
left join public.haven_sessions hs on hs.review_id = br.id and hs.scope = 'audit'
order by br.created_at desc;

grant select on public.available_booking_slots to anon, authenticated, service_role;
grant select on public.admin_lead_overview to service_role;
